// Source/packaging guard, not a substitute for platform compilation/runtime tests.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const text = p => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const spec = JSON.parse(text('script/desktop-resources.json'));
assert.equal(spec.browser.windows_runtime, 'evergreen');
assert.equal(spec.browser.macos_runtime, 'wkwebview');
assert(!spec.webview2, 'Do not acquire a private browser runtime');
assert.equal(spec.speech.sha256, '921e4cf8686fdd993dcd081a5da5b6c365bfde1162e72b08d75ac75289920b1f');
const windows = text('crates/browser_preview/src/windows.rs');
assert(windows.includes('GetAvailableCoreWebView2BrowserVersionString(PCWSTR::null()'));
assert.match(windows, /CreateCoreWebView2EnvironmentWithOptions\(\s*PCWSTR::null\(\)/);
assert(!windows.includes('runtime_directory') && !windows.includes('version != runtime_version'));
const browser = text('crates/browser_preview/src/browser_preview.rs');
assert(browser.includes('BrowserResources::system()'));
assert(!browser.includes('manifest.json'), 'Browser must work without bundled speech resources');
assert(browser.includes('browser-install-runtime'), 'Explain missing runtime and link to Microsoft');
const mac = text('crates/browser_preview/src/macos.rs');
for (const native of ['kind = "framework"', 'WKWebView', 'takeSnapshotWithConfiguration:', 'setHidden:', 'didFinishNavigation:', 'goBack', 'goForward']) assert(mac.includes(native), native);
assert(text('crates/browser_preview/src/native.rs').includes('mod macos_host'));
const acquire = text('script/acquire-desktop-resources.ps1');
assert(!acquire.includes('Get-VerifiedResource $specification.webview2'));
assert(acquire.includes('Private browser runtimes are no longer bundled'));
const bundle = text('script/bundle-windows.ps1');
assert(!bundle.includes('icacls.exe'), 'No private browser runtime ACL required');
const installer = text('crates/zed/resources/windows/zed.iss');
assert(!installer.includes('GrantDesktopRuntimeAccess'));
assert(installer.includes('if not IsUpdating() then'), 'Never delete the active runtime during staged updates');
assert(installer.includes("{app}\\resources\\desktop\\webview2"), 'Clean up obsolete private runtime on normal upgrade');
for (const expected of ['{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}', 'HKLM32', 'HKCU32', 'HKCU64', "'pv'", 'IsWebView2Version', 'https://go.microsoft.com/fwlink/p/?LinkId=2124703', '/silent /install', 'Get-AuthenticodeSignature', 'Microsoft Corporation', 'EnsureSystemWebView2();']) assert(installer.includes(expected), expected);
assert(!installer.includes('Source: "MicrosoftEdgeWebview2Setup.exe"'), 'Bootstrapper must not be installed as app payload');
assert(installer.includes('CurPageID = wpFinished') && installer.includes('WizardForm.FinishedLabel.Caption'), 'Keep missing-runtime instructions visible on the final setup page');
console.log('System browser source/packaging checks passed; platform compilation and runtime checks remain required.');
